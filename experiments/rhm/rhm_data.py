"""Random Hierarchy Model data generation for autoregressive modeling.

Generates sequences with controllable hierarchical structure following
Cagnetta & Wyart (2024). Each sequence of length s^L has multi-scale
correlations: tokens at distance s^ℓ are correlated through shared
level-(ℓ+1) features in the composition hierarchy.

The hierarchy is defined by composition rules sampled once and fixed.
Each feature at level ℓ has m rules, each mapping to an s-tuple of
features at level ℓ-1. Sequences are generated by starting from a
random root feature and recursively expanding via randomly chosen rules.
"""

import numpy as np


def generate_rules(v, s, L, m, seed=0):
    """Sample composition rules for the hierarchy.

    Returns list of L arrays, each of shape (v, m, s).
    rules[ℓ][f, r, :] = the s-tuple produced by rule r of feature f at level ℓ.
    Level 0 is the top of the hierarchy (root → level-L features),
    level L-1 is the bottom (level-1 features → leaf tokens).
    """
    rng = np.random.default_rng(seed)
    return [rng.integers(0, v, size=(v, m, s)) for _ in range(L)]


def generate_rules_distinct(v, s, L, m, seed=0):
    """Sample composition rules with m DISTINCT s-tuples per feature.

    Same shape/semantics as generate_rules ((v, m, s) per level), but the m rules
    of each feature are guaranteed distinct (sampled without replacement from the
    v^s possible s-tuples). generate_rules uses rng.integers (with replacement), so
    a feature can hold repeated rules and the legal-tuple set is denser/collision-
    prone. This "distinct" variant is the canonical RHM construction and is used to
    control tuple-space occupancy m/v^(s-1), which governs how identifiable the
    high-level features are from the leaves (see RHM_DEEP_COMPOSITION_README.md).

    Kept separate from generate_rules so all prior experiments stay reproducible.
    """
    rng = np.random.default_rng(seed)
    rules = []
    for _ in range(L):
        layer = np.empty((v, m, s), dtype=np.int64)
        for f in range(v):
            codes = rng.choice(v ** s, size=m, replace=False)  # m distinct tuples
            for i in range(s):
                layer[f, :, i] = (codes // (v ** i)) % v
        rules.append(layer)
    return rules


def generate_rules_invertible(v, s, L, m, seed=0):
    """Sample composition rules that are COLLISION-FREE across features.

    Same shape/semantics as generate_rules ((v, m, s) per level), but at each
    level the m*v produced s-tuples are all DISTINCT across the whole level (not
    just within a feature, as generate_rules_distinct guarantees). Sampled
    without replacement from the v^s possible s-tuples, so every legal tuple maps
    to exactly one (feature, rule) pair.

    Consequence: the bottom-up parse (leaves -> root) is UNIQUE and EXACT — the
    RHM becomes a properly invertible tree code. This is what the active-editing
    control experiment needs so that "the true root of an (on-grammar) sequence"
    is well-defined ground truth, closing the "the controller defines its own
    target" loophole. Requires v*m <= v^s (always true for the canonical
    v=8,s=2,m<=4: 8*m <= 64).

    Kept separate from the other generators so all prior experiments stay
    reproducible.
    """
    rng = np.random.default_rng(seed)
    n_codes = v ** s
    if v * m > n_codes:
        raise ValueError(
            f"collision-free rules require v*m <= v**s (got v*m={v * m}, v**s={n_codes})"
        )
    powers = v ** np.arange(s)
    rules = []
    for _ in range(L):
        codes = rng.choice(n_codes, size=v * m, replace=False).reshape(v, m)  # all distinct
        layer = np.empty((v, m, s), dtype=np.int64)
        for i in range(s):
            layer[:, :, i] = (codes // (v ** i)) % v
        # sanity: decode round-trips
        assert np.array_equal((layer * powers).sum(axis=2).reshape(-1),
                              codes.reshape(-1)), "tuple encode/decode mismatch"
        rules.append(layer)
    return rules


def build_inverse_maps(rules):
    """Per-level table mapping an s-tuple code -> the feature that produces it.

    rules[level] has shape (v, m, s) and maps level-(L-level) features down to
    level-(L-level-1) features (rules[L-1] maps level-1 features to leaves).
    inverse_maps[level][code] = f if some rule of feature f produces that tuple,
    else -1 (off-grammar). For collision-free rules the assignment is unique; for
    denser rule sets the LAST writer wins (parse is then only approximate).
    """
    v, m, s = rules[0].shape
    powers = v ** np.arange(s)
    maps = []
    for layer in rules:
        table = np.full(v ** s, -1, dtype=np.int64)
        codes = (layer * powers).sum(axis=2)  # (v, m)
        for f in range(v):
            for r in range(m):
                table[int(codes[f, r])] = f
        maps.append(table)
    return maps


def parse_leaves(leaves, rules, inverse_maps=None):
    """Batched bottom-up parse: leaf sequences -> (roots, valid).

    leaves: (B, s^L) int array. Returns (roots (B,), valid (B,) bool) where
    valid[i] is False if any s-tuple encountered on the way up is off-grammar
    (produced by no feature). For collision-free rules (generate_rules_invertible)
    a valid parse recovers the exact generating root. Off-grammar tuples are
    replaced by feature 0 so the parse can continue (root is meaningless when
    valid is False).
    """
    v, m, s = rules[0].shape
    L = len(rules)
    if inverse_maps is None:
        inverse_maps = build_inverse_maps(rules)
    powers = v ** np.arange(s)
    current = np.asarray(leaves, dtype=np.int64)
    valid = np.ones(current.shape[0], dtype=bool)
    for level in range(L - 1, -1, -1):  # invert from leaves (L-1) up to root (0)
        batch, width = current.shape
        tuples = current.reshape(batch, width // s, s)
        codes = (tuples * powers).sum(axis=2)  # (batch, width//s)
        feats = inverse_maps[level][codes]
        valid &= (feats >= 0).all(axis=1)
        current = np.where(feats < 0, 0, feats)
    return current[:, 0], valid


def generate_sequences(rules, n_sequences, seed=0):
    """Generate sequences by traversing the hierarchy.

    Each sequence starts with a random root feature from {0, ..., v-1}
    and expands L times using randomly chosen rules.

    Returns array of shape (n_sequences, s^L) with tokens from {0, ..., v-1}.
    """
    rng = np.random.default_rng(seed)
    L = len(rules)
    v, m, s = rules[0].shape
    seq_len = s ** L

    sequences = np.empty((n_sequences, seq_len), dtype=np.int64)

    for i in range(n_sequences):
        current = np.array([rng.integers(0, v)])
        for ell in range(L):
            rule_choices = rng.integers(0, m, size=len(current))
            next_level = np.empty(len(current) * s, dtype=np.int64)
            for j in range(len(current)):
                next_level[j * s:(j + 1) * s] = rules[ell][current[j], rule_choices[j]]
            current = next_level
        sequences[i] = current

    return sequences


def generate_sequences_batched(rules, n_sequences, seed=0, batch_size=10000):
    """Vectorized sequence generation for large corpora.

    Same output as generate_sequences but processes in batches using
    vectorized numpy operations.
    """
    rng = np.random.default_rng(seed)
    L = len(rules)
    v, m, s = rules[0].shape
    seq_len = s ** L

    sequences = np.empty((n_sequences, seq_len), dtype=np.int64)

    for start in range(0, n_sequences, batch_size):
        end = min(start + batch_size, n_sequences)
        bs = end - start

        current = rng.integers(0, v, size=(bs, 1))
        for ell in range(L):
            n_features = current.shape[1]
            rule_choices = rng.integers(0, m, size=(bs, n_features))
            next_level = np.empty((bs, n_features * s), dtype=np.int64)
            for j in range(n_features):
                chosen = rules[ell][current[:, j], rule_choices[:, j]]  # (bs, s)
                next_level[:, j * s:(j + 1) * s] = chosen
            current = next_level

        sequences[start:end] = current

    return sequences


def sequences_to_corpus(sequences):
    """Flatten sequences into a 1D token array (corpus)."""
    return sequences.reshape(-1)


def make_corpus(v, s, L, m, n_tokens, rule_seed=0, seq_seed=1):
    """End-to-end: generate rules and a corpus of n_tokens tokens.

    Returns (corpus, rules, meta) where:
    - corpus is a 1D int64 array of tokens
    - rules is the list of composition rule arrays
    - meta is a dict with generation parameters
    """
    rules = generate_rules(v, s, L, m, seed=rule_seed)
    seq_len = s ** L
    n_sequences = (n_tokens + seq_len - 1) // seq_len

    sequences = generate_sequences_batched(rules, n_sequences, seed=seq_seed)
    corpus = sequences_to_corpus(sequences)[:n_tokens]

    meta = {
        "v": v, "s": s, "L": L, "m": m,
        "seq_len": seq_len,
        "n_sequences": n_sequences,
        "n_tokens": len(corpus),
        "vocab_size": v,
        "rule_seed": rule_seed,
        "seq_seed": seq_seed,
    }

    return corpus, rules, meta
